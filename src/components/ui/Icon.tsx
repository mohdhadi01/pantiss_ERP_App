export type IconName = keyof typeof registry;
export type IconSource = IconName | (string & {});

export interface IconProps {
  name: IconSource;
  size?: number;
  color?: string;
  strokeWidth?: number;
  style?: object;
}

export const Icon: React.FC<IconProps> = ({
  name,
  size = 20,
  color = '#64748b',
  strokeWidth = 2,
  style,
}) => {
  const Component =
    registry[name as IconName] ?? HelpCircle;

  if (__DEV__ && !(name in registry)) {
    console.warn(`[Icon] Unknown icon name "${name}" — rendering HelpCircle.`);
  }

  return <Component size={size} color={color} strokeWidth={strokeWidth} style={style} />;
};
